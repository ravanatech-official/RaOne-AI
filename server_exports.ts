import { Document, Packer, Paragraph, TextRun, HeadingLevel } from 'docx';
import PptxGenJSModule from 'pptxgenjs';
import ExcelJS from 'exceljs';
import PDFDocument from 'pdfkit';

const PptxGenJS: any = (PptxGenJSModule as any)?.default || PptxGenJSModule;

export interface ExportDocumentInput {
  title: string;
  content: string;
  slides?: Array<{
    slideNumber?: number;
    title: string;
    subtitle?: string;
    bulletPoints?: string[];
    callout?: string;
  }>;
}

// Spreadsheet Formula-Injection Neutralizer (prevents =CMD(), +1+1, @SUM CSV/Excel exploits)
export function sanitizeSpreadsheetCell(value: string): string {
  const trimmed = String(value ?? '');
  if (/^[=+\-@\t\r]/.test(trimmed)) {
    return `'${trimmed}`;
  }
  return trimmed;
}

export async function generateTrueDocxBuffer(input: ExportDocumentInput): Promise<Buffer> {
  const lines = (input.content || '').split(/\r?\n/);
  const children: Paragraph[] = [
    new Paragraph({
      text: input.title || 'RaOne Document',
      heading: HeadingLevel.TITLE,
    }),
  ];

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) {
      children.push(new Paragraph({ text: '' }));
      continue;
    }
    if (line.startsWith('### ')) {
      children.push(new Paragraph({ text: line.slice(4), heading: HeadingLevel.HEADING_3 }));
    } else if (line.startsWith('## ')) {
      children.push(new Paragraph({ text: line.slice(3), heading: HeadingLevel.HEADING_2 }));
    } else if (line.startsWith('# ')) {
      children.push(new Paragraph({ text: line.slice(2), heading: HeadingLevel.HEADING_1 }));
    } else if (line.startsWith('- ') || line.startsWith('* ')) {
      children.push(
        new Paragraph({
          text: line.slice(2).replace(/\*\*/g, ''),
          bullet: { level: 0 },
        })
      );
    } else {
      children.push(
        new Paragraph({
          children: [new TextRun({ text: line.replace(/\*\*/g, ''), size: 22 })],
        })
      );
    }
  }

  const doc = new Document({
    creator: 'RaOne AI DocuStudio',
    title: input.title || 'RaOne Document',
    sections: [{ children }],
  });

  return Packer.toBuffer(doc);
}

export async function generateTruePptxBuffer(input: ExportDocumentInput): Promise<Buffer> {
  const pres = new PptxGenJS();
  pres.author = 'RaOne AI DocuStudio';
  pres.title = input.title || 'RaOne Presentation';
  pres.layout = 'LAYOUT_WIDE';

  const slides =
    input.slides && input.slides.length > 0
      ? input.slides
      : [
          {
            slideNumber: 1,
            title: input.title || 'Executive Overview',
            subtitle: 'Generated by RaOne AI DocuStudio',
            bulletPoints: (input.content || '')
              .split(/\r?\n/)
              .map((l) => l.replace(/^[-*#]+\s*/, '').trim())
              .filter(Boolean)
              .slice(0, 6),
          },
        ];

  for (const s of slides) {
    const slide = pres.addSlide();
    slide.background = { color: '0F172A' };
    slide.addText(s.title || input.title, {
      x: 0.7,
      y: 0.5,
      w: '88%',
      h: 0.8,
      fontSize: 26,
      bold: true,
      color: '38BDF8',
    });

    if (s.subtitle) {
      slide.addText(s.subtitle, {
        x: 0.7,
        y: 1.25,
        w: '88%',
        h: 0.45,
        fontSize: 14,
        color: '94A3B8',
      });
    }

    const bullets = (s.bulletPoints || []).filter(Boolean);
    if (bullets.length > 0) {
      slide.addText(
        bullets.map((b) => ({ text: b, options: { bullet: true, breakLine: true } })),
        {
          x: 0.8,
          y: 1.9,
          w: '86%',
          h: 3.6,
          fontSize: 16,
          color: 'E2E8F0',
          valign: 'top',
        }
      );
    }

    if (s.callout) {
      slide.addText(s.callout, {
        x: 0.7,
        y: 5.7,
        w: '88%',
        h: 0.7,
        fontSize: 12,
        italic: true,
        color: '7DD3FC',
        fill: { color: '1E293B' },
      });
    }
  }

  const out = await pres.write({ outputType: 'nodebuffer' });
  return Buffer.isBuffer(out) ? out : Buffer.from(out);
}

export async function generateTrueXlsxBuffer(input: ExportDocumentInput): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'RaOne AI DocuStudio';
  workbook.created = new Date();
  const sheet = workbook.addWorksheet('Document Data');

  const lines = (input.content || '').split(/\r?\n/);
  const mdTableRows = lines.filter((l) => l.includes('|') && !/^\s*\|?[\s:-]+\|/.test(l));

  if (mdTableRows.length > 0) {
    mdTableRows.forEach((row, idx) => {
      const cells = row
        .split('|')
        .map((c) => c.trim())
        .filter((c, i, arr) => !(i === 0 && c === '') && !(i === arr.length - 1 && c === ''));
      if (cells.length > 0) {
        const added = sheet.addRow(cells.map((c) => sanitizeSpreadsheetCell(c)));
        if (idx === 0) {
          added.font = { bold: true, color: { argb: 'FFFFFFFF' } };
          added.fill = {
            type: 'pattern',
            pattern: 'solid',
            fgColor: { argb: 'FF0F172A' },
          };
        }
      }
    });
  } else {
    const header = sheet.addRow(['Section / Line', 'Content']);
    header.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    header.fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: 'FF0F172A' },
    };
    lines
      .map((l) => l.trim())
      .filter(Boolean)
      .forEach((line, idx) => {
        sheet.addRow([`Line ${idx + 1}`, sanitizeSpreadsheetCell(line)]);
      });
  }

  sheet.columns.forEach((col) => {
    col.width = 36;
  });

  const arrayBuffer = await workbook.xlsx.writeBuffer();
  return Buffer.from(arrayBuffer);
}

export async function generateTruePdfBuffer(input: ExportDocumentInput): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50, size: 'A4' });
    const chunks: Buffer[] = [];
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.fontSize(20).fillColor('#0F172A').text(input.title || 'RaOne Document');
    doc.moveDown(0.5);
    doc.fontSize(9).fillColor('#64748B').text(`Generated by RaOne AI DocuStudio • ${new Date().toISOString()}`);
    doc.moveDown(1);

    const lines = (input.content || '').split(/\r?\n/);
    for (const raw of lines) {
      const line = raw.trim();
      if (!line) {
        doc.moveDown(0.4);
      } else if (line.startsWith('# ')) {
        doc.moveDown(0.4).fontSize(15).fillColor('#047857').text(line.slice(2));
      } else if (line.startsWith('## ')) {
        doc.moveDown(0.3).fontSize(13).fillColor('#0F172A').text(line.slice(3));
      } else {
        doc.fontSize(11).fillColor('#1E293B').text(line.replace(/\*\*/g, ''), { lineGap: 3 });
      }
    }

    doc.end();
  });
}
